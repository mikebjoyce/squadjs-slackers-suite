/**
 * ╔═══════════════════════════════════════════════════════════════╗
 * ║   WHAT ACTUALLY EXPLAINS TICKET MARGIN, IF NOT BALANCE?       ║
 * ╚═══════════════════════════════════════════════════════════════╝
 *
 * §2.6 established that |mu delta| — everything the scrambler controls —
 * explains only 2.4% of ticket-margin variance (r=0.155). That leaves 97.6%
 * unaccounted for. This script asks what's in that remainder: is any of it
 * controllable (population, round length), or is most of it the layer itself
 * (different RAAS versions have different objective counts and therefore
 * different maximum ticket bleed, which has nothing to do with team balance)?
 *
 * Nested OLS, same pattern as clan-block-margin.js: add one block at a time,
 * report the LRT (normal-errors likelihood-ratio test via n*log(ssRes ratio),
 * chi-sq(added params)) for whether that block earns its keep over what came
 * before it.
 *
 * Two groups of blocks, kept deliberately separate:
 *
 *   PRE-ROUND (knowable/settable before the round starts, so actually
 *   candidate levers): |mu delta| (1), + effective population (2),
 *   + layer identity (3, map+version, top N as dummies, rest "Other").
 *
 *   IN-ROUND (generated by the round itself, reported separately and never
 *   folded into the "controllable" total): round duration (4). RAAS ends
 *   when one side's tickets hit zero — a blowout produces both the large
 *   ticket margin AND the short duration as joint effects of the same
 *   in-round bleed rate. Duration is not a pre-round input and, tested
 *   first, silently steals credit that belongs to layer identity: with
 *   duration in the model layer's ΔR^2 is 0.057 (p<0.001); with duration
 *   OUT, layer's ΔR^2 drops to 0.007 (p=0.725, not significant) — most of
 *   layer's apparent effect was really proxying for how long that map's
 *   rounds tend to run, not an independent ticket-economy signal. So block 3
 *   is evaluated on top of blocks 1-2 only, and duration is reported last,
 *   labeled as an outcome correlate rather than a driver.
 *
 * RAAS only, same selection as mu-predicts-margin.js (Elo_RoundHistory joined
 * to Elo_RoundPlayers — no snapshot join needed, so this gets the larger
 * ENDGAME-adjacent sample rather than the LIVE-roster-only subset).
 *
 *   node --max-old-space-size=4096 analysis/ticket-margin-drivers.js
 */

import {
  newestExport,
  loadExport,
  table,
  describe,
  correlation,
  isCompetitive,
  effectivePopulation,
  MIN_EFFECTIVE_PLAYERS,
  fmt,
  pStr,
  chiSqP
} from './load-export.js';

const DEFAULT_MU = 25.0;
const MIN_PER_TEAM = 20;
const TOP_N_LAYERS = 10;

const exp = loadExport(newestExport());
const rounds = table(exp, 'Elo_RoundHistory');
const roundPlayers = table(exp, 'Elo_RoundPlayers');

console.log('\n═══ WHAT EXPLAINS TICKET MARGIN, BEYOND BALANCE? ═══\n');

/* ─── Map/version identity, collapsed across the underscore/space naming
 * inconsistency already documented in scramble-replay.js's layer matching. */
function layerKey(layerName) {
  const norm = String(layerName || '').replace(/[_-]+/g, ' ').trim();
  return norm.replace(/\s+/g, ' ').toLowerCase();
}

const byRound = new Map();
for (const rp of roundPlayers) {
  if (rp.roundHistoryId == null) continue;
  if (!byRound.has(rp.roundHistoryId)) byRound.set(rp.roundHistoryId, []);
  byRound.get(rp.roundHistoryId).push(rp);
}

const records = [];
const rejected = { noPlayers: 0, nonCompetitive: 0, noTickets: 0, lowPop: 0, tooSmall: 0, noDuration: 0 };

for (const round of rounds) {
  const players = byRound.get(round.id);
  if (!players || players.length === 0) {
    rejected.noPlayers++;
    continue;
  }
  if (!isCompetitive(round.layerName)) {
    rejected.nonCompetitive++;
    continue;
  }
  if (!Number.isFinite(round.ticketDiff)) {
    rejected.noTickets++;
    continue;
  }
  if (!Number.isFinite(round.roundDuration) || round.roundDuration <= 0) {
    rejected.noDuration++;
    continue;
  }
  const effPop = effectivePopulation(players);
  if (effPop < MIN_EFFECTIVE_PLAYERS) {
    rejected.lowPop++;
    continue;
  }
  const t1 = players.filter((p) => Number(p.teamID) === 1);
  const t2 = players.filter((p) => Number(p.teamID) === 2);
  const mu1 = t1.map((p) => p.muBefore).filter(Number.isFinite);
  const mu2 = t2.map((p) => p.muBefore).filter(Number.isFinite);
  if (mu1.length < MIN_PER_TEAM || mu2.length < MIN_PER_TEAM) {
    rejected.tooSmall++;
    continue;
  }
  const meanMu1 = mu1.reduce((s, v) => s + v, 0) / mu1.length;
  const meanMu2 = mu2.reduce((s, v) => s + v, 0) / mu2.length;

  records.push({
    id: round.id,
    layer: layerKey(round.layerName),
    ticketDiff: Math.abs(round.ticketDiff),
    absMuDelta: Math.abs(meanMu1 - meanMu2),
    effPop,
    roundDurationMin: round.roundDuration / 60000
  });
}

console.log('─── Round selection ───');
console.log(`  usable rounds:            ${records.length}`);
console.log(`  dropped, no player rows:  ${rejected.noPlayers}`);
console.log(`  dropped, non-RAAS:        ${rejected.nonCompetitive}`);
console.log(`  dropped, no ticket data:  ${rejected.noTickets}`);
console.log(`  dropped, no duration:     ${rejected.noDuration}`);
console.log(`  dropped, under ${MIN_EFFECTIVE_PLAYERS} eff pop: ${rejected.lowPop}`);
console.log(`  dropped, under ${MIN_PER_TEAM}/side:  ${rejected.tooSmall}\n`);

if (records.length < 60) {
  console.log('Too few usable rounds to say anything. Stopping.\n');
  process.exit(0);
}

/* ─── Layer buckets: top N by frequency, everything else pooled ────────── */
const layerCounts = new Map();
for (const r of records) layerCounts.set(r.layer, (layerCounts.get(r.layer) || 0) + 1);
const topLayers = [...layerCounts.entries()]
  .sort((a, b) => b[1] - a[1])
  .slice(0, TOP_N_LAYERS)
  .map(([k]) => k);
const topLayerSet = new Set(topLayers);
for (const r of records) r.layerBucket = topLayerSet.has(r.layer) ? r.layer : 'other';

console.log(`  layers as their own dummy (top ${TOP_N_LAYERS} by n): ${topLayers.join(', ')}\n`);

/* ─── OLS via normal equations, same helper as clan-block-margin.js ────── */
function ols(rows, y) {
  const n = rows.length;
  const k = rows[0].length + 1;
  const X = rows.map((r) => [1, ...r]);
  const XtX = Array.from({ length: k }, () => new Array(k).fill(0));
  const Xty = new Array(k).fill(0);
  for (let i = 0; i < n; i++) {
    for (let a = 0; a < k; a++) {
      Xty[a] += X[i][a] * y[i];
      for (let b = 0; b < k; b++) XtX[a][b] += X[i][a] * X[i][b];
    }
  }
  const A = XtX.map((row, i) => [...row, Xty[i]]);
  for (let col = 0; col < k; col++) {
    let piv = col;
    for (let r = col + 1; r < k; r++) if (Math.abs(A[r][col]) > Math.abs(A[piv][col])) piv = r;
    [A[col], A[piv]] = [A[piv], A[col]];
    const pv = A[col][col] || 1e-12;
    for (let c = col; c <= k; c++) A[col][c] /= pv;
    for (let r = 0; r < k; r++) {
      if (r === col) continue;
      const f = A[r][col];
      for (let c = col; c <= k; c++) A[r][c] -= f * A[col][c];
    }
  }
  const beta = A.map((row) => row[k]);
  const predict = (row) => beta[0] + row.reduce((s, v, j) => s + v * beta[j + 1], 0);
  let ssRes = 0;
  let ssTot = 0;
  const my = y.reduce((s, v) => s + v, 0) / n;
  for (let i = 0; i < n; i++) {
    const p = predict(rows[i]);
    ssRes += (y[i] - p) ** 2;
    ssTot += (y[i] - my) ** 2;
  }
  const r2 = 1 - ssRes / ssTot;
  return { beta, predict, r2, n, k, ssRes };
}

function lrt(prev, next, dfAdded, n) {
  const stat = n * Math.log(prev.ssRes / next.ssRes);
  const p = chiSqP(stat, dfAdded);
  return { stat, p };
}

/* ─── Nested blocks ──────────────────────────────────────────────────────
 * mu -> + population -> + duration -> + layer identity. */

const y = records.map((r) => r.ticketDiff);

const layerDummyCols = topLayers; // 'other' is the reference level, dropped
function layerRow(r) {
  return layerDummyCols.map((l) => (r.layerBucket === l ? 1 : 0));
}

const m1 = ols(records.map((r) => [r.absMuDelta]), y);
const m2 = ols(records.map((r) => [r.absMuDelta, r.effPop]), y);
const m3 = ols(records.map((r) => [r.absMuDelta, r.effPop, ...layerRow(r)]), y);

console.log('═══ Nested OLS on |ticket diff| — PRE-ROUND factors only ═══\n');
console.log(`  1. |mu delta| alone                          R^2 = ${fmt(m1.r2, 4)}`);
console.log(`  2. + effective population                    R^2 = ${fmt(m2.r2, 4)}   (ΔR^2 = ${fmt(m2.r2 - m1.r2, 4)})`);
console.log(`  3. + layer identity (${topLayers.length} dummies)              R^2 = ${fmt(m3.r2, 4)}   (ΔR^2 = ${fmt(m3.r2 - m2.r2, 4)})`);

const l2 = lrt(m1, m2, 1, records.length);
const l3 = lrt(m2, m3, layerDummyCols.length, records.length);
console.log('\n  significance of each block, on top of what came before:');
console.log(`    + population   LRT chi-sq(1)               = ${fmt(l2.stat, 2)}   p = ${pStr(l2.p)}`);
console.log(`    + layer        LRT chi-sq(${layerDummyCols.length})              = ${fmt(l3.stat, 2)}   p = ${pStr(l3.p)}`);

console.log(`\n  total pre-round variance explained: R^2 = ${fmt(m3.r2, 4)} (was ${fmt(m1.r2, 4)} on mu alone)`);
console.log(`  still unexplained by anything knowable before the round: ${fmt((1 - m3.r2) * 100, 1)}%\n`);

/* ─── Duration: reported, not credited ──────────────────────────────────
 * RAAS ends on ticket depletion, so duration and margin are joint outputs
 * of the same in-round bleed — this is a correlate, not a lever. */
const m4 = ols(records.map((r) => [r.absMuDelta, r.effPop, ...layerRow(r), r.roundDurationMin]), y);
const l4 = lrt(m3, m4, 1, records.length);
console.log('═══ Round duration — reported separately, NOT a pre-round lever ═══\n');
console.log(`  + round duration (on top of block 3)         R^2 = ${fmt(m4.r2, 4)}   (ΔR^2 = ${fmt(m4.r2 - m3.r2, 4)})`);
console.log(`    LRT chi-sq(1) = ${fmt(l4.stat, 2)}   p = ${pStr(l4.p)}`);
console.log('  Huge and "significant," but not usable: a blowout produces both the large ticket');
console.log('  margin and the short round length as joint effects of the same in-round ticket');
console.log('  bleed rate — you cannot set round duration in advance to buy this. Quoted here so');
console.log('  it doesn\'t get rediscovered and mistaken for an actionable driver later.\n');

/* ─── Per-layer mean ticket margin — is this a ticket-economy story? ────── */
console.log('═══ Mean ticket diff by layer (top layers by n) ═══\n');
for (const l of topLayers) {
  const d = describe(records.filter((r) => r.layerBucket === l).map((r) => r.ticketDiff));
  console.log(`  ${l.padEnd(24)} n=${String(d.n).padStart(4)}   mean ${fmt(d.mean, 1).padStart(6)}   median ${fmt(d.median, 1).padStart(6)}   sd ${fmt(d.sd, 1)}`);
}
const otherD = describe(records.filter((r) => r.layerBucket === 'other').map((r) => r.ticketDiff));
console.log(`  ${'(other)'.padEnd(24)} n=${String(otherD.n).padStart(4)}   mean ${fmt(otherD.mean, 1).padStart(6)}   median ${fmt(otherD.median, 1).padStart(6)}   sd ${fmt(otherD.sd, 1)}`);

/* ─── Population and duration correlations, for scale ───────────────────── */
console.log('\n═══ Simple correlations, for scale ═══\n');
console.log(`  r(effective pop, ticket diff)     = ${fmt(correlation(records.map((r) => r.effPop), y).r, 3)}`);
console.log(`  r(round duration, ticket diff)    = ${fmt(correlation(records.map((r) => r.roundDurationMin), y).r, 3)}`);
console.log(`  r(round duration, |mu delta|)     = ${fmt(correlation(records.map((r) => r.roundDurationMin), records.map((r) => r.absMuDelta)).r, 3)}  (collinearity check)`);

/* ─── Verdict ─────────────────────────────────────────────────────────── */
console.log('═══ Verdict ═══\n');
const preRoundGain = m3.r2 - m1.r2;
if (l3.p < 0.05 && preRoundGain > 0.03) {
  console.log('  Layer identity is a real, non-trivial pre-round driver, independent of duration —');
  console.log('  the ticket economy itself (objective/lane count per RAAS version) moves margin');
  console.log('  independent of team balance and is knowable before the round starts.');
} else {
  console.log('  Nothing knowable before the round starts meaningfully closes the gap. Population');
  console.log(`  adds a little (ΔR^2 ${fmt(m2.r2 - m1.r2, 4)}); layer identity, once duration\'s`);
  console.log('  collinearity is removed, adds almost nothing (ΔR^2 ' + fmt(m3.r2 - m2.r2, 4) + ', p=' + pStr(l3.p) + ').');
  console.log(`  Pre-round factors together explain ${fmt(m3.r2 * 100, 1)}% of ticket-margin variance —`);
  console.log('  barely above mu alone. The only thing that correlates strongly with margin is round');
  console.log('  duration, and that is generated DURING the round by the same blowout dynamics that');
  console.log('  produce the margin — not a settable input. There is no hidden structural lever here;');
  console.log('  the remaining variance is consistent with genuine within-round randomness (individual');
  console.log('  play, momentum swings, admin calls) that this data cannot resolve into anything');
  console.log('  actionable pre-round.');
}
console.log('');
